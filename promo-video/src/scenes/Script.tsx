import type React from "react";
import { AbsoluteFill, interpolate, useCurrentFrame } from "remotion";
import { SceneTitle } from "../components/SceneTitle";
import { Caret, Terminal } from "../components/Terminal";
import { Checkbox, ClickRipple, Cursor, Icon, type IconName } from "../components/ui";
import { mix, progress, reveal, travel } from "../anim";
import { C, FONT } from "../theme";

const BAR = { x: 760, y: 190, w: 1060, h: 84 };
const CY = BAR.y + BAR.h / 2;
// Fixed widths so the cursor can find each control.
const UPDATE = { w: 150, x: BAR.x + BAR.w - 24 - 150 };
const RUN = { w: 220, x: UPDATE.x - 12 - 220 };
const COPY = { w: 180, x: RUN.x - 12 - 180 };
const ADMIN = { w: 270, x: COPY.x - 12 - 270 };

const SCRIPT = [
  "# Generated by UpInstall",
  "winget upgrade --id Git.Git -e",
  "winget upgrade --id OpenJS.NodeJS.LTS -e",
  "winget upgrade --id Microsoft.PowerToys -e",
];
const OUTPUT: { text: string; color?: string }[] = [
  { text: "Found Git [Git.Git] Version 2.56.0.4", color: C.terminalText },
  { text: "This application is licensed to you by its owner.", color: C.textFaint },
  { text: "  ██████████████████████████████  68.4 MB / 68.4 MB", color: "#60A5FA" },
  { text: "Successfully verified installer hash", color: C.terminalText },
  { text: "Starting package install...", color: C.terminalText },
  { text: "Successfully installed", color: C.prompt },
  { text: "Found Node.js LTS [OpenJS.NodeJS.LTS] Version 26.13.0", color: C.terminalText },
];

/** Scene: copy the generated script, or run it in Windows Terminal (optionally as administrator). */
export const Script = () => {
  const frame = useCurrentFrame();

  // cursor path: Copy script → Run as administrator → Run in terminal
  const p1 = travel(frame, 18, 22);
  const p2 = travel(frame, 66, 18);
  const p3 = travel(frame, 96, 18);
  const copyPt = { x: COPY.x + COPY.w / 2, y: CY };
  const adminPt = { x: ADMIN.x + 28, y: CY };
  const runPt = { x: RUN.x + RUN.w / 2, y: CY };
  let cx = mix(1300, copyPt.x, p1);
  let cy = mix(1060, copyPt.y, p1);
  cx = mix(cx, adminPt.x, p2);
  cy = mix(cy, adminPt.y, p2);
  cx = mix(cx, runPt.x, p3);
  cy = mix(cy, runPt.y, p3);

  const clickAt = (f: number) => interpolate(frame, [f, f + 4, f + 9], [0, 1, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });
  const copyPress = clickAt(42);
  const adminPress = clickAt(86);
  const runPress = clickAt(116);

  const copied = reveal(frame, 46, 10) * (1 - reveal(frame, 80, 10));
  const admin = reveal(frame, 89, 8);
  const term = reveal(frame, 122, 18);

  const chars = Math.max(0, (frame - 128) * 9);
  let budget = chars;
  const typed = SCRIPT.map((line) => {
    const take = Math.max(0, Math.min(line.length, budget));
    budget -= line.length;
    return line.slice(0, take);
  });
  const scriptDone = chars >= SCRIPT.join("").length;
  const outShown = scriptDone ? Math.floor((frame - 128 - SCRIPT.join("").length / 9) / 4) : 0;

  return (
    <AbsoluteFill style={{ fontFamily: FONT, color: C.text }}>
      <SceneTitle
        left={110}
        top={300}
        width={600}
        eyebrow="Scripts & terminal"
        headline={"Copy it.\nOr run it."}
        subline="UpInstall writes the exact winget commands. Paste them anywhere, or open Windows Terminal, even as admin."
        headlineSize={110}
      />

      {/* UpInstall's command bar */}
      <div
        style={{
          position: "absolute",
          left: BAR.x,
          top: BAR.y,
          width: BAR.w,
          height: BAR.h,
          boxSizing: "border-box",
          borderRadius: 18,
          background: "linear-gradient(160deg, rgba(40,44,58,0.97), rgba(28,31,40,0.97))",
          border: `1px solid ${C.edge}`,
          boxShadow: "0 30px 70px rgba(0,0,0,0.45)",
          ...barIn(frame),
        }}
      >
        <div style={{ position: "absolute", left: 28, top: 0, height: BAR.h, display: "flex", alignItems: "center", fontSize: 22 }}>
          <span style={{ fontWeight: 650 }}>3</span>&nbsp;
          <span style={{ color: C.textDim }}>selected</span>
        </div>
        <div style={{ position: "absolute", left: ADMIN.x - BAR.x, top: 0, width: ADMIN.w, height: BAR.h, display: "flex", alignItems: "center", gap: 12, fontSize: 19, padding: "0 14px", boxSizing: "border-box" }}>
          <Checkbox checked={admin} size={26} />
          Run as administrator
        </div>
        <BarButton x={COPY.x - BAR.x} w={COPY.w} icon="copy" label="Copy script" press={copyPress} />
        <BarButton x={RUN.x - BAR.x} w={RUN.w} icon="terminal" label="Run in terminal" press={runPress} />
        <BarButton x={UPDATE.x - BAR.x} w={UPDATE.w} icon="download" label="Update" primary press={0} />
      </div>

      {/* "Copied" tooltip */}
      <div
        style={{
          position: "absolute",
          left: copyPt.x - 130,
          top: BAR.y + BAR.h + 16,
          width: 260,
          height: 52,
          borderRadius: 12,
          background: "#282C3A",
          border: "1px solid rgba(255,255,255,0.12)",
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
          gap: 10,
          fontSize: 19,
          opacity: copied,
          translate: `0px ${(1 - copied) * -10}px`,
        }}
      >
        <Icon name="check" size={20} color={C.success} strokeWidth={2.4} />
        Copied 3 commands
      </div>

      <div style={{ position: "absolute", left: BAR.x, top: 330 }}>
        <Terminal
          width={BAR.w}
          height={570}
          title="Administrator: Windows PowerShell"
          admin
          fontSize={21}
          style={{ opacity: term, translate: `0px ${(1 - term) * 60}px`, scale: String(mix(0.95, 1, term)) }}
        >
          {typed.map((line, i) =>
            line.length > 0 ? (
              <div key={i} style={{ color: i === 0 ? C.textFaint : C.terminalText }}>
                {i > 0 ? <span style={{ color: C.prompt }}>PS&gt; </span> : null}
                {line}
                {!scriptDone && line.length < SCRIPT[i].length ? <Caret frame={frame} /> : null}
              </div>
            ) : null,
          )}
          {scriptDone ? <div style={{ height: 18 }} /> : null}
          {OUTPUT.slice(0, Math.max(0, outShown)).map((l, i) => (
            <div key={i} style={{ color: l.color }}>
              {l.text}
            </div>
          ))}
        </Terminal>
      </div>

      <ClickRipple x={copyPt.x} y={copyPt.y} t={progress(frame, 45, 14)} />
      <ClickRipple x={adminPt.x} y={adminPt.y} t={progress(frame, 89, 14)} />
      <ClickRipple x={runPt.x} y={runPt.y} t={progress(frame, 119, 14)} />
      <Cursor
        x={cx - 6}
        y={cy - 6}
        press={Math.max(copyPress, adminPress, runPress)}
        opacity={reveal(frame, 18, 8) * (1 - reveal(frame, 136, 10))}
      />
    </AbsoluteFill>
  );
};

const BarButton: React.FC<{ x: number; w: number; icon: IconName; label: string; press: number; primary?: boolean }> = ({
  x,
  w,
  icon,
  label,
  press,
  primary,
}) => (
  <div
    style={{
      position: "absolute",
      left: x,
      top: (BAR.h - 52) / 2,
      width: w,
      height: 52,
      borderRadius: 11,
      background: primary ? "#2F7BE6" : `rgba(255,255,255,${0.07 + 0.1 * press})`,
      border: "1px solid rgba(255,255,255,0.08)",
      display: "flex",
      alignItems: "center",
      justifyContent: "center",
      gap: 10,
      fontSize: 19,
      fontWeight: primary ? 650 : 500,
      scale: String(1 - 0.06 * press),
      boxSizing: "border-box",
    }}
  >
    <Icon name={icon} size={21} color={primary ? "white" : C.textDim} />
    {label}
  </div>
);

const barIn = (frame: number): React.CSSProperties => {
  const t = reveal(frame, 4, 22);
  return { opacity: t, translate: `0px ${(1 - t) * -40}px` };
};
